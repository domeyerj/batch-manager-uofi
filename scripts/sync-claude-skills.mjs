#!/usr/bin/env node
/**
 * Generate thin Claude Code wrappers in .claude/skills/<name>/SKILL.md for every
 * shared skill in .agents/skills/<name>/SKILL.md (Gemini CLI reads .agents/skills
 * natively; Claude Code reads .claude/skills). Safe to re-run; it overwrites only
 * the wrappers it generated (marked with GENERATED_MARK) and removes wrappers whose
 * shared skill no longer exists.
 *
 *   npm run skills:sync          # write wrappers
 *   npm run skills:sync -- --check   # exit 1 if wrappers are missing/out of date (CI)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, '.agents', 'skills');
const DEST = join(ROOT, '.claude', 'skills');
const GENERATED_MARK = '<!-- generated by scripts/sync-claude-skills.mjs — edit .agents/skills instead -->';
const check = process.argv.includes('--check');

function field(text, key) {
  const fm = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const m = fm && fm[1].match(new RegExp(`^${key}:\\s*(.*)$`, 'm'));
  return m ? m[1].trim() : '';
}

function wrapper(name, description) {
  return `---
name: ${name}
description: ${description}
---
${GENERATED_MARK}

This is a thin wrapper. The shared skill, used by both Claude and Gemini, is the source of truth.

Read \`.agents/skills/${name}/SKILL.md\` at the repository root now and follow it exactly. To change the procedure, edit that shared file, log the change in \`changelog/\`, and run \`npm run skills:sync\`.
`;
}

const names = existsSync(SRC) ? readdirSync(SRC).filter((n) => existsSync(join(SRC, n, 'SKILL.md'))) : [];
let drift = 0;

for (const name of names) {
  const text = readFileSync(join(SRC, name, 'SKILL.md'), 'utf8');
  const skillName = field(text, 'name') || name;
  const description = field(text, 'description');
  if (!description) { console.warn(`skip ${name}: no description in front matter`); continue; }
  const out = join(DEST, name, 'SKILL.md');
  const want = wrapper(skillName, description);
  const have = existsSync(out) ? readFileSync(out, 'utf8') : null;
  if (have === want) continue;
  if (have !== null && !have.includes(GENERATED_MARK)) {
    console.warn(`skip ${name}: .claude/skills/${name}/SKILL.md is hand-written (no generated marker)`);
    continue;
  }
  drift++;
  if (check) { console.log(`out of date: .claude/skills/${name}/SKILL.md`); continue; }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, want);
  console.log(`wrote .claude/skills/${name}/SKILL.md`);
}

if (existsSync(DEST)) {
  for (const name of readdirSync(DEST)) {
    const f = join(DEST, name, 'SKILL.md');
    if (names.includes(name) || !existsSync(f) || !readFileSync(f, 'utf8').includes(GENERATED_MARK)) continue;
    drift++;
    if (check) { console.log(`orphaned: .claude/skills/${name}`); continue; }
    rmSync(join(DEST, name), { recursive: true, force: true });
    console.log(`removed orphaned .claude/skills/${name}`);
  }
}

if (check && drift) { console.log(`\n${drift} wrapper(s) need syncing — run: npm run skills:sync`); process.exit(1); }
console.log(drift ? `Synced ${drift} wrapper(s).` : 'Claude skill wrappers are up to date.');
